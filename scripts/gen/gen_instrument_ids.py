#!/usr/bin/env python3
"""Generate TS instrument-id tables from crates/dsp/instruments.catalog.json.

The catalog is the single source of truth for engine instrument ids and the
public group→id map. Rust's `Instrument` enum in kernels.rs must match the
catalog (verified here); the TS tables are generated, never hand-edited.

Usage:
  python3 scripts/gen/gen_instrument_ids.py          # write generated files
  python3 scripts/gen/gen_instrument_ids.py --check  # exit 1 if stale/mismatched
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "crates" / "dsp" / "instruments.catalog.json"
KERNELS = ROOT / "crates" / "dsp" / "src" / "kernels.rs"
OUT_TS = ROOT / "packages" / "core" / "src" / "instrument-ids.generated.ts"
HEADER = (
    "/* eslint-disable */\n"
    "// @generated by scripts/gen/gen_instrument_ids.py — DO NOT EDIT.\n"
    "// Source of truth: crates/dsp/instruments.catalog.json\n"
)


def load_catalog() -> dict:
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    instruments = data["instruments"]
    groups = data["groups"]
    ids = [row["id"] for row in instruments]
    if ids != list(range(len(ids))):
        raise SystemExit(f"catalog ids must be contiguous from 0: got {ids}")
    keys = [row["key"] for row in instruments]
    if len(set(keys)) != len(keys):
        raise SystemExit("catalog instrument keys must be unique")
    by_key = {row["key"]: row for row in instruments}
    for g in groups:
        if g["instrument"] not in by_key:
            raise SystemExit(f"group {g['group']!r} references unknown instrument {g['instrument']!r}")
    return data


def parse_rust_enum() -> list[tuple[int, str]]:
    text = KERNELS.read_text(encoding="utf-8")
    match = re.search(r"pub enum Instrument \{([^}]+)\}", text, re.S)
    if not match:
        raise SystemExit("could not find pub enum Instrument in kernels.rs")
    items: list[tuple[int, str]] = []
    for line in match.group(1).splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("/"):
            continue
        mm = re.match(r"(\w+)\s*=\s*(\d+)", stripped)
        if mm:
            items.append((int(mm.group(2)), mm.group(1)))
    return sorted(items)


def verify_rust(catalog: dict) -> list[str]:
    errors: list[str] = []
    rust = parse_rust_enum()
    expected = [(row["id"], row["rust"]) for row in catalog["instruments"]]
    if rust != expected:
        errors.append(
            "Rust Instrument enum does not match crates/dsp/instruments.catalog.json\n"
            f"  rust:     {rust}\n"
            f"  catalog:  {expected}"
        )
    # from_u32 arms
    text = KERNELS.read_text(encoding="utf-8")
    fn = re.search(r"pub fn from_u32\(v: u32\) -> Self \{([^}]+(?:\{[^}]*\}[^}]*)*)\}", text, re.S)
    if not fn:
        # simpler: require each id arm
        body = text
    else:
        body = fn.group(0)
    for row in catalog["instruments"]:
        if row["id"] == 0:
            continue  # default arm
        needle = f"{row['id']} => Self::{row['rust']}"
        if needle not in body:
            errors.append(f"from_u32 missing arm for {needle}")
    return errors


def render_ts(catalog: dict) -> str:
    instruments = catalog["instruments"]
    groups = catalog["groups"]
    lines = [HEADER, "/** Engine-side instrument ids (crates/dsp kernels::Instrument). */\n"]
    lines.append("export const INST = {\n")
    for row in instruments:
        lines.append(f"  {row['tsConst']}: {row['id']},\n")
    lines.append("} as const;\n\n")
    lines.append("export type InstrumentId = (typeof INST)[keyof typeof INST];\n\n")
    lines.append("/** Canonical public group names (plus aliases) accepted by the engine host. */\n")
    lines.append("export type InstrumentGroup =\n")
    for g in groups:
        lines.append(f'  | "{g["group"]}"\n')
    lines.append(";\n\n")
    lines.append("/** Group name → engine instrument id. */\n")
    lines.append("export const GROUP_TO_INSTRUMENT: Record<InstrumentGroup, number> = {\n")
    by_key = {row["key"]: row for row in instruments}
    for g in groups:
        inst = by_key[g["instrument"]]
        comment = " // placeholder" if g.get("placeholder") else ""
        lines.append(f'  "{g["group"]}": INST.{inst["tsConst"]},{comment}\n')
    lines.append("};\n\n")
    lines.append("/** id → canonical key (for diagnostics / offline tools). */\n")
    lines.append("export const INSTRUMENT_KEY_BY_ID: readonly string[] = [\n")
    for row in instruments:
        lines.append(f'  "{row["key"]}",\n')
    lines.append("];\n")
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = load_catalog()
    errors = verify_rust(catalog)
    generated = render_ts(catalog)
    if errors:
        print("INSTRUMENT ID CHECK FAIL:", file=sys.stderr)
        for err in errors:
            print(f"- {err}", file=sys.stderr)
        return 1
    if args.check:
        if not OUT_TS.is_file():
            print(f"missing generated file {OUT_TS.relative_to(ROOT)}", file=sys.stderr)
            return 1
        current = OUT_TS.read_text(encoding="utf-8")
        if current != generated:
            print(
                f"{OUT_TS.relative_to(ROOT)} is stale — run "
                "python3 scripts/gen/gen_instrument_ids.py",
                file=sys.stderr,
            )
            return 1
        print(
            f"instrument-ids OK ({len(catalog['instruments'])} instruments, "
            f"{len(catalog['groups'])} groups; rust enum matches catalog)"
        )
        return 0
    OUT_TS.parent.mkdir(parents=True, exist_ok=True)
    OUT_TS.write_text(generated, encoding="utf-8")
    print(f"wrote {OUT_TS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
